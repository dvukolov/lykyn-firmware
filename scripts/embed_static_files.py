#!/usr/bin/env python3
"""Gzip-embed the Next.js export for the Lykyn on-device dashboard."""

from __future__ import annotations

import gzip
import sys
from html.parser import HTMLParser
from pathlib import Path


class AssetReferenceParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.urls = []

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        url = attributes.get("src") if tag == "script" else attributes.get("href")
        if url and url.startswith("/") and not url.startswith("//"):
            self.urls.append(url.split("?", 1)[0].split("#", 1)[0])


CONTENT_TYPES = {
    ".css": "text/css",
    ".js": "application/javascript",
    ".woff2": "font/woff2",
    ".woff": "font/woff",
    ".ttf": "font/ttf",
    ".ico": "image/x-icon",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".html": "text/html",
    ".json": "application/json",
}


def _bytes_as_c(data: bytes) -> str:
    return ", ".join(str(b) for b in data)


def find_assets(webapp_out: Path) -> list[tuple[str, Path]]:
    index_html = webapp_out / "index.html"
    if not index_html.is_file():
        raise FileNotFoundError(f"Exported dashboard not found: {index_html}")
    parser = AssetReferenceParser()
    parser.feed(index_html.read_text(encoding="utf-8"))
    found: list[tuple[str, Path]] = []
    seen = set()
    # The HTML itself is served at / (and /index.html).
    found.append(("/", index_html))
    seen.add("/")
    for url in parser.urls:
        if url in seen:
            continue
        path = webapp_out / url.lstrip("/")
        if not path.is_file():
            raise FileNotFoundError(f"Dashboard references {url}, but it was not in {webapp_out}")
        found.append((url, path))
        seen.add(url)
    return found


def embed(webapp_out, header_path, cpp_path, namespace="lykyn_dashboard"):
    webapp_out = Path(webapp_out)
    header_path = Path(header_path)
    cpp_path = Path(cpp_path)
    assets = find_assets(webapp_out)

    entries = []
    total_raw = 0
    total_gz = 0
    for url, path in assets:
        raw = path.read_bytes()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total_raw += len(raw)
        total_gz += len(gz)
        ctype = CONTENT_TYPES.get(path.suffix, "application/octet-stream")
        if url == "/":
            ctype = "text/html"
        entries.append((url, ctype, gz))
        print(f"  {url}: {len(raw)} -> {len(gz)} gzip bytes")

    print(f"Total: {total_raw} raw, {total_gz} gzip ({100 * total_gz / max(total_raw, 1):.1f}%)")

    h_lines = [
        "// Auto-generated by scripts/embed_static_files.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace esphome {",
        f"namespace {namespace} {{",
        "",
        "struct StaticFile {",
        "  const uint8_t *data;",
        "  size_t size;",
        "  const char *content_type;",
        "  const char *url;",
        "};",
        "",
        f"extern const size_t STATIC_FILES_COUNT;",
        "extern const StaticFile STATIC_FILES[];",
        "",
        f"}}  // namespace {namespace}",
        "}  // namespace esphome",
        "",
    ]
    header_path.write_text("\n".join(h_lines))

    cpp = [
        "// Auto-generated by scripts/embed_static_files.py. Do not edit.",
        '#include "static_files.h"',
        "",
        "namespace esphome {",
        f"namespace {namespace} {{",
        "",
    ]
    for i, (url, ctype, gz) in enumerate(entries):
        cpp.append(f"static const uint8_t STATIC_FILE_{i}_DATA[] = {{{_bytes_as_c(gz)}}};")
        cpp.append(f"static const size_t STATIC_FILE_{i}_SIZE = {len(gz)};")
        cpp.append("")
    cpp.append(f"const size_t STATIC_FILES_COUNT = {len(entries)};")
    cpp.append("const StaticFile STATIC_FILES[] = {")
    for i, (url, ctype, gz) in enumerate(entries):
        cpp.append(
            f'    {{STATIC_FILE_{i}_DATA, STATIC_FILE_{i}_SIZE, "{ctype}", "{url}"}},'
        )
    cpp.append("};")
    cpp.append("")
    cpp.append(f"}}  // namespace {namespace}")
    cpp.append("}  // namespace esphome")
    cpp.append("")
    cpp_path.write_text("\n".join(cpp))
    print(f"Wrote {header_path} and {cpp_path}")
    return total_gz


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) != 3:
        print(
            "usage: embed_static_files.py <webapp/out> <static_files.h> <static_files.cpp>",
            file=sys.stderr,
        )
        return 2
    embed(argv[0], argv[1], argv[2])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
